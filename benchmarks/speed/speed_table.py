"""Markdown latency tables from the results of benchmarks/speed/speed_table.sh (median ms, fastest in bold).

    python benchmarks/speed/speed_table.py [results/speed/table]     # writes <dir>/table.md and prints it
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

PRESETS = ("fp32", "bf16", "int8", "fp8")
EXTRACTORS = ("superpoint", "disk", "alike", "xfeat", "dedode", "dedode-g", "dad", "ripe", "aliked",
              "raco-aliked", "rdd", "sift", "orb")
PIPELINES = ("superpoint-lightglue", "disk-lightglue", "xfeat-lightglue", "aliked-lightglue",
             "raco-aliked-lightglue", "rdd-lightglue", "loftr")
ROMAV2_PRESETS = ("bf16", "int8", "fp8")
ROMAV2_ENGINES = ("eager", "compile", "compile-full")


def _cells(times: dict[str, float | str | None], keys) -> list[str]:
    """``eager / compile`` per key, the fastest number of the row in bold (``fail``: the run crashed)."""
    values = [v for v in times.values() if isinstance(v, float | int)]
    best = min(values) if values else None

    def fmt(value):
        if value is None or isinstance(value, str):
            return value or "-"
        text = f"{value:.1f}" if value >= 10 else f"{value:.2f}"
        return f"**{text}**" if value == best else text

    return [" / ".join(fmt(times.get((key, engine))) for engine in ("eager", "compile"))
            if any(times.get((key, e)) is not None for e in ("eager", "compile")) else "" for key in keys]


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("directory", nargs="?", default="results/speed/table", type=Path)
    args = parser.parse_args()

    extract, pair, gpu = defaultdict(dict), defaultdict(dict), ""
    log = args.directory / "run.log"
    for line in log.read_text().splitlines() if log.exists() else ():  # crashed runs (results below override)
        if line.startswith("FAILED ") and not line.startswith("FAILED romav2"):
            model, preset, engine = line.removeprefix("FAILED ").split("|")
            table = pair if model.endswith("-lightglue") or model == "loftr" else extract
            table[model][(preset, engine)] = "fail"
    for line in (args.directory / "sparse.jsonl").read_text().splitlines():
        r = json.loads(line)
        model, preset, engine = r["tag"].split("|")
        gpu = r["gpu"]
        if r.get("pair_level"):
            pair[model][(preset, engine)] = r["match_median_ms"]
        else:
            extract[model][(preset, engine)] = r["extract_median_ms"]
            if model.endswith("-lightglue"):  # pair forward: both images extracted, then LightGlue
                pair[model][(preset, engine)] = 2 * r["extract_median_ms"] + r["match_median_ms"]

    romav2 = defaultdict(dict)
    for path in args.directory.glob("romav2_*.json"):
        r = json.loads(path.read_text())
        gpu, key = r["gpu"], r["engine"]
        best = romav2[r["preset"]].get(key)
        romav2[r["preset"]][key] = r["median_ms"] if best is None else min(best, r["median_ms"])

    out = [f"# Inference latency ({gpu})", "",
           ("Median ms per call, one configuration per process, 10 warmups + 50 timed calls (CUDA events). "
            "Generated by `benchmarks/speed/speed_table.py` from `benchmarks/speed/speed_table.sh`."), ""]

    out += ["## RoMaV2 (dense)", "",
            ("Preloaded bidirectional forward, mega1500 setting (800² LR + 1024² HR), B=1. Compiled engines: "
             "best of two processes. Speed-up: over `bf16` in the same engine."), "",
            "| preset | eager | compile | compile-full | speed-up (compile-full) |", "|---|---|---|---|---|"]
    base = romav2.get("bf16", {}).get("compile-full")
    for preset in ROMAV2_PRESETS:
        times = romav2.get(preset, {})
        values = [times.get(e) for e in ROMAV2_ENGINES]
        best = min((v for v in values if v is not None), default=None)
        cells = ["-" if v is None else (f"**{v:.1f}**" if v == best else f"{v:.1f}") for v in values]
        full = times.get("compile-full")
        ratio = f"{base / full:.2f}x" if base and full else "-"
        out.append(f"| `{preset}` | " + " | ".join(cells) + f" | {ratio} |")

    out += ["", "## Sparse extractors", "",
            ("`extract` of one MegaDepth image, 1200 px long side, 4096 keypoints; each cell is "
             "`eager / compile`. SIFT and ORB are OpenCV (fp32, eager)."), "",
            "| model | " + " | ".join(PRESETS) + " |", "|---|" + "---|" * len(PRESETS)]
    for model in EXTRACTORS:
        if model in extract:
            out.append(f"| {model} | " + " | ".join(_cells(extract[model], PRESETS)) + " |")

    out += ["", "## Pair matching", "",
            ("One image pair at 1200 px: `*-lightglue` = 2 x `extract` + LightGlue `match_features` (4096 "
             "keypoints per image), the column being LightGlue's preset; the extractor runs the same preset "
             "when it has one, else `bf16` (ALIKED / RaCo-ALIKED int8 and fp8, RDD int8). LoFTR: `match` of "
             "the pair, all coarse matches. Each cell is `eager / compile`."), "",
            "| pipeline | " + " | ".join(PRESETS) + " |", "|---|" + "---|" * len(PRESETS)]
    for model in PIPELINES:
        if model in pair:
            out.append(f"| {model} | " + " | ".join(_cells(pair[model], PRESETS)) + " |")

    failed = sorted(
        f"{model}|{preset}|{engine}" for table in (extract, pair) for model, times in table.items()
        for (preset, engine), value in times.items() if value == "fail"
    )
    if failed:
        out += ["", "## Failures", ""]
        for tag in failed:  # the first sentence of the exception line in the run's stderr
            err = args.directory / f"{tag.replace('|', '_')}.err"
            lines = [line for line in err.read_text().splitlines() if "Error" in line] if err.exists() else []
            message = lines[-1].strip().split(". ")[0] if lines else "see the .err file"
            out.append(f"- `{tag}`: {message}")

    text = "\n".join(out) + "\n"
    (args.directory / "table.md").write_text(text)
    print(text)


if __name__ == "__main__":
    main()
